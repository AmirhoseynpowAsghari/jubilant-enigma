"""
kgrid.py -- k-space grid and pairing kernel for arbitrary (U, Delta_t, V_SO).
Part of the corrected reconstruction of
  AmirhoseynpowAsghari/power-absorbed-in-the-presence-of-external-time-dependent-perturbation
Parameterised over (U, Delta_t, n, V_SO) so that every parameter set of arXiv:2607.02812
can be solved with the same stage-1 code.

GRID CORRECTION (audit finding F-02, fixed 2026-10-24)
------------------------------------------------------
The original reconstruction used the repo's ENDPOINT grid k = linspace(0, pi, Nk) with
uniform weights 1/Nk^2.  That quadrature double-counts the Gamma/X/M-symmetric corner
and edge points of the quarter zone (they carry the same weight as interior points while
representing half/quarter cells), so every stage-1 quantity carried an O(Delta_k),
V_SO-dependent bias that had NOT converged at Nk=160:

    endpoint grid, master set V_SO=0:  Tc(Nk=40/80/160) = 0.293986 / 0.286054 / 0.282122

The corrected grid is the MIDPOINT rule k_i = (i + 1/2) pi / Nk, for which the uniform
weight (pi/Nk)^2 is exact to O(Nk^-2) with no edge overcounting (the integrand is smooth
and symmetric on the quarter zone; the midpoint rule also avoids sampling the measure-zero
Gamma point).  Convergence with the corrected grid (verified in test_fixes.py and recorded
per set in the stage-1 JSONs via the solve_set convergence check):

    midpoint grid, master set V_SO=0:  Tc(Nk=40/80/160) = 0.278211 / 0.278211 / 0.278211

Stage 2 (kgrid_ua.py) always used the midpoint rule; the two stages now integrate the
SAME measure.  Numbers produced before this fix are archived in
archive/pre_f02_baseline/ and must not be mixed with the corrected ones.
"""
from __future__ import annotations

import json
import time
import numpy as np
from scipy.optimize import fsolve, brentq

from parameters_tc import T, Nk_DEF


def midpoint_k(Nk: int) -> np.ndarray:
    """Midpoint nodes of [0, pi]: k_i = (i + 1/2) * pi / Nk, i = 0..Nk-1."""
    if int(Nk) < 4:
        raise ValueError(f"Nk must be >= 4, got {Nk}")
    return (np.arange(int(Nk)) + 0.5) * np.pi / int(Nk)


def build_kgrid(V_SO, U, Delta_t, Nk=Nk_DEF):
    """eps[:, :, s] and the pairing `term` on the midpoint quarter-zone grid (F-02 fix).

    The uniform 1/Nk^2 average used by gap_equations.make_residual is the correct
    midpoint-rule weight for <...>_k over the quarter zone [0, pi]^2 (the full zone is
    generated by the kx -> -kx, ky -> -ky symmetries of eps_s(k)).
    """
    kx = midpoint_k(Nk)
    ky = midpoint_k(Nk)
    KX, KY = np.meshgrid(kx, ky, indexing="ij")
    sqrt_sin = np.sqrt(np.sin(KX) ** 2 + np.sin(KY) ** 2)
    cos_sum = np.cos(KX) + np.cos(KY)
    s_k_factor = 0.5 * (np.cos(KX) + np.cos(KY))
    sp = np.array([1.0, -1.0])
    eps = np.zeros((Nk, Nk, 2))
    eps[:, :, 0] = -2.0 * T * cos_sum - 2.0 * V_SO * sqrt_sin
    eps[:, :, 1] = -2.0 * T * cos_sum + 2.0 * V_SO * sqrt_sin
    term = (U + 8.0 * Delta_t * s_k_factor[..., None]
            + 4.0 * (Delta_t / T) * V_SO * sp[None, None, :] * sqrt_sin[..., None])
    return eps, term
